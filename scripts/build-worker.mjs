// Package the static build (dist/) into a single self-contained Worker module.
//
// Why this exists: this app is designed for Cloudflare Workers Static Assets (assets-only,
// no code — see wrangler.jsonc), which is the default deploy path. But some environments cannot
// use the Static Assets upload flow: it needs a per-session upload JWT, and any setup that
// rewrites the Cloudflare API request (e.g. a corporate/CI proxy that injects the account token
// on every request) can clobber that JWT → 401 on /workers/assets/upload. A plain Worker SCRIPT
// upload is unaffected, so this script embeds the built files into a tiny Worker that serves them
// and applies the SAME headers from public/_headers (single source of truth — the CSP egress lock
// travels with the response).
//
// Output: worker-dist/index.js + worker-dist/wrangler.jsonc. Deploy with:
//   npm run build && node scripts/build-worker.mjs && npx wrangler deploy --config worker-dist/wrangler.jsonc
// Forks should prefer `npm run deploy`; byobanana.com itself runs this path. See docs/DEPLOYING.md.
import { readFileSync, readdirSync, mkdirSync, writeFileSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveSiteUrl, prodHost } from "./site-url.mjs";

const root = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const distDir = join(root, "dist");
const outDir = join(root, "worker-dist");

// `npm run build` already rewrote dist/ to SITE_URL (see scripts/site-url.mjs); here we only derive
// the matching PROD_HOST so the Worker's host-aware noindex, www→apex, and preview redirect target
// the deployer's own domain. Default SITE_URL = the author's origin ⇒ PROD_HOST = "byobanana.com".
const PROD_HOST = prodHost(resolveSiteUrl());

const CONTENT_TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".xml": "application/xml; charset=utf-8",
  ".webmanifest": "application/manifest+json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".avif": "image/avif",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
  // Correct MIME lets the jSquash glues use WebAssembly.instantiateStreaming (performance
  // only — both fall back to ArrayBuffer instantiation on application/octet-stream).
  ".wasm": "application/wasm",
};

function contentType(path) {
  const dot = path.lastIndexOf(".");
  return CONTENT_TYPES[path.slice(dot)] ?? "application/octet-stream";
}

// Parse public/_headers (Cloudflare format) into [{ prefix, headers }]. A line starting with
// "/" opens a rule; indented "Name: value" lines add headers until the next rule/blank line.
function parseHeaders(text) {
  const rules = [];
  let current = null;
  for (const raw of text.split("\n")) {
    if (raw.startsWith("#") || raw.trim() === "") continue;
    if (raw.startsWith("/")) {
      current = { prefix: raw.trim().replace(/\*$/, ""), headers: {} };
      rules.push(current);
    } else if (current) {
      const idx = raw.indexOf(":");
      if (idx > 0) current.headers[raw.slice(0, idx).trim()] = raw.slice(idx + 1).trim();
    }
  }
  return rules;
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const headerRules = parseHeaders(readFileSync(join(root, "public", "_headers"), "utf8"));

// Assets are stored base64-encoded so the Worker is binary-safe (future images/fonts/wasm won't
// corrupt); the Worker decodes to bytes at serve time.
const assets = {};
for (const file of walk(distDir)) {
  const rel = "/" + relative(distDir, file).split("\\").join("/");
  if (rel === "/_headers") continue; // config, not a served asset
  assets[rel] = { ct: contentType(rel), b64: readFileSync(file).toString("base64") };
}

const worker = `// GENERATED by scripts/build-worker.mjs — do not edit. Serves the static build with the
// public/_headers CSP applied to EVERY response (200s, redirects, and errors). Regenerate after
// \`npm run build\`. Beyond serving assets it does light host/path hardening (see fetch below):
// www→apex + index.html/dir canonicalization (single hop), host-aware noindex, cache-control,
// and malformed-URL / method guarding.
const ASSETS = ${JSON.stringify(assets)};
const HEADER_RULES = ${JSON.stringify(headerRules)};
const PROD_HOST = ${JSON.stringify(PROD_HOST)};
// PREVIEW_REDIRECT: when true, every non-production host (the *.workers.dev preview, localhost) 301s
// to the production apex (PROD_HOST, from SITE_URL) instead of serving a duplicate site. Set to false
// to restore preview-only serving (the guard below then short-circuits, leaving preview behavior
// unchanged). Leave it false until the production apex is live. See docs/DEPLOYING.md.
const PREVIEW_REDIRECT = true;

function bytes(b64) {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i += 1) out[i] = bin.charCodeAt(i);
  return out;
}

// Merge every matching _headers rule (prefix match) for a path onto a response's headers, so the
// CSP + security headers travel with 200s AND with redirects/404/405/400 responses.
function headersFor(path, ct) {
  const h = new Headers();
  if (ct) h.set("content-type", ct);
  for (const rule of HEADER_RULES) {
    if (path.startsWith(rule.prefix)) {
      for (const [name, value] of Object.entries(rule.headers)) h.set(name, value);
    }
  }
  return h;
}

export default {
  fetch(request) {
    const url = new URL(request.url);
    // url.hostname is already lowercased and port-stripped. The production host is crawlable;
    // every other host (workers.dev preview, localhost, apex-before-DNS) gets a noindex tag so
    // the preview cannot outrank byobanana.com. Decided from the ORIGINAL request host.
    const noindex = url.hostname !== PROD_HOST;
    const finish = (response) => {
      if (noindex) response.headers.set("X-Robots-Tag", "noindex");
      return response;
    };
    const head = request.method === "HEAD";

    // Method guard: only GET/HEAD serve assets. Cache-Control: no-store so a proxy never caches
    // an error against \`/assets/*\` (headersFor would otherwise apply the immutable rule).
    if (request.method !== "GET" && !head) {
      const h = headersFor(url.pathname, "text/plain; charset=utf-8");
      h.set("Allow", "GET, HEAD");
      h.set("Cache-Control", "no-store");
      return finish(new Response("Method Not Allowed", { status: 405, headers: h }));
    }

    // Decode the path once; malformed percent-encoding (e.g. "/%zz") returns 400, never a 500.
    let path;
    try {
      path = decodeURIComponent(url.pathname);
    } catch {
      const h = headersFor("/", "text/plain; charset=utf-8");
      h.set("Cache-Control", "no-store");
      return finish(new Response(head ? null : "Bad Request", { status: 400, headers: h }));
    }

    // Compute ONE canonical redirect covering host + scheme + path so www + /index.html is a
    //   single hop:
    //   www.byobanana.com/*            -> https://byobanana.com/*  (host, port, https at once)
    //   http://byobanana.com/*         -> https://byobanana.com/*  (Cloudflare "Always Use HTTPS"
    //                                     is a separate zone setting the Worker can't assume)
    //   <path>/index.html              -> <path>/                  (and "/index.html" -> "/")
    //   <dir> (no trailing slash)      -> <dir>/                   when <dir>/index.html exists
    // Mutate a CLONED URL and serialize it, so the port, query string, and percent-encoding are
    // all preserved (building Location by hand dropped the port and turned %23/%3F into real
    // fragment/query delimiters).
    const target = new URL(url);
    let mustRedirect = false;
    // PREVIEW_REDIRECT (see const above): fold any non-production host into the SAME single hop as
    // the canonicalizers below. OFF ⇒ the && short-circuits and mustRedirect is untouched.
    if (PREVIEW_REDIRECT && target.hostname !== PROD_HOST && target.hostname !== "www." + PROD_HOST) {
      target.protocol = "https:";
      target.hostname = PROD_HOST;
      target.port = "";
      mustRedirect = true;
    }
    if (target.hostname === "www." + PROD_HOST) {
      target.hostname = PROD_HOST;
      target.port = "";
      mustRedirect = true;
    }
    if (target.hostname === PROD_HOST && target.protocol === "http:") {
      target.protocol = "https:";
      mustRedirect = true;
    }
    if (path.endsWith("/index.html")) {
      target.pathname = path.slice(0, -"index.html".length);
      mustRedirect = true;
    } else if (!path.endsWith("/") && ASSETS[path + "/index.html"]) {
      target.pathname = path + "/";
      mustRedirect = true;
    }
    if (mustRedirect) {
      const h = headersFor(target.pathname, null);
      h.set("Location", target.toString());
      h.set("Cache-Control", "no-store");
      return finish(new Response(null, { status: 301, headers: h }));
    }

    // Resolve the asset ("/" and directory paths map to index.html).
    let lookup = path;
    if (lookup === "/" || lookup.endsWith("/")) lookup += "index.html";
    const asset = ASSETS[lookup];
    if (!asset) {
      const h = headersFor(lookup, "text/plain; charset=utf-8");
      // Override any \`/assets/*\` immutable rule: a 404 must not be cached for a year.
      h.set("Cache-Control", "no-store");
      return finish(new Response(head ? null : "Not Found", { status: 404, headers: h }));
    }
    const headers = headersFor(lookup, asset.ct);
    // Content-hashed assets under /assets/* keep the _headers immutable rule; every other
    // successful asset (index.html, /landing.css, /theme-init.js) must revalidate so a deploy
    // that drops a hashed file is never referenced by stale cached HTML.
    if (!lookup.startsWith("/assets/")) headers.set("Cache-Control", "no-cache");
    const body = head ? null : bytes(asset.b64);
    return finish(new Response(body, { status: 200, headers }));
  },
};
`;

// Written as raw JSONC (not JSON.stringify) so the custom-domain routes can ship commented-out,
// ready to activate once the byobanana.com zone exists in this account.
const wranglerConfig = `{
  "name": "nano-banana-web",
  "main": "index.js",
  "compatibility_date": "2026-07-01",
  "workers_dev": true,
  // Custom domains activated after the byobanana.com zone went live on this account:
  "routes": [
    { "pattern": "byobanana.com", "custom_domain": true },
    { "pattern": "www.byobanana.com", "custom_domain": true }
  ]
}
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "index.js"), worker);
writeFileSync(join(outDir, "wrangler.jsonc"), wranglerConfig);

const totalKb = (Buffer.byteLength(worker) / 1024).toFixed(1);
console.log(`Wrote worker-dist/index.js (${totalKb} KiB, ${Object.keys(assets).length} assets)`);
for (const p of Object.keys(assets)) console.log("  " + p);
